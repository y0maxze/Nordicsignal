def _point_in_time_features(result):
    ticker = str((result or {}).get("ticker") or "").upper().replace(".OL", "")
    opp = (result or {}).get("opportunity") or {}
    reversal = (result or {}).get("reversal") or {}
    metrics = reversal.get("metrics") or {}
    components = opp.get("components") or {}
    smart_money = (((result or {}).get("insider_signal_v2") or {}).get("smart_money") or {})
    score = shadow._latest_score(ticker) or {}
    event_risk = evidence_v2._recent_event_risk(ticker)
    prior_evidence = evidence_v2._opportunity_evidence(ticker)
    identity = identity_runtime._current_identity()

    benchmark_symbol = None
    benchmark_context = None
    try:
        benchmark_symbol, benchmark_context = opportunity_shadow._context_for_result(result)
    except Exception:
        benchmark_context = None
    benchmark_context = benchmark_context or {}

    materiality = [
        _num(item.get("materiality_ratio_pct"))
        for item in (event_risk.get("items") or [])
        if _num(item.get("materiality_ratio_pct")) is not None
    ]

    feature_payload = {
        "captured_at": _now(),
        "base_score": {
            "total": score.get("total"),
            "fundamentals": score.get("fundamentals"),
            "valuation": score.get("valuation"),
            "sentiment": score.get("sentiment"),
            "insider": score.get("insider"),
            "source": score.get("source"),
        },
        "opportunity": {
            "label": opp.get("label"),
            "score": opp.get("score"),
            "confidence": opp.get("confidence"),
            "components": components,
        },
        "trend": evidence_v2._trend_dimension({"payload": result}),
        "smart_money": smart_money,
        "recent_event_risk": event_risk,
        "market_context": {
            "benchmark_id": market.BENCHMARK_ID if benchmark_context else None,
            "benchmark_symbol": benchmark_symbol if benchmark_context else None,
            **benchmark_context,
        },
        "prior_opportunity_evidence": prior_evidence,
        "policy": "Frozen point-in-time research features only; no activation or trading output.",
    }

    return {
        "model_version": MODEL_VERSION,
        "source_signal_model_id": str(identity.get("signal_model_id") or "unknown"),
        "ticker": ticker,
        "market_date": _market_date(result),
        "observed_at": str((result or {}).get("generated_at") or _now()),
        "entry_price": _num(tracking._entry_price(result or {})),
        "base_score": _num(score.get("total")),
        "fundamentals": _num(score.get("fundamentals")),
        "valuation": _num(score.get("valuation")),
        "sentiment": _num(score.get("sentiment")),
        "insider_score": _num(score.get("insider")),
        "opportunity_label": str(opp.get("label") or "NO_OPPORTUNITY"),
        "opportunity_score": _num(opp.get("score")),
        "opportunity_confidence": str(opp.get("confidence") or "low"),
        "reversal_score": _num(components.get("reversal_score") if components.get("reversal_score") is not None else reversal.get("score")),
        "reversal_regime": str(components.get("reversal_regime") or reversal.get("regime") or ""),
        "rsi14": _num(metrics.get("rsi14")),
        "macd_histogram": _num(metrics.get("macd_histogram")),
        "volume_ratio": _num(metrics.get("volume_ratio") if metrics.get("volume_ratio") is not None else components.get("volume_ratio")),
        "volume_confirmation": str(metrics.get("volume_confirmation") or components.get("volume_state") or "NONE"),
        "current_drawdown_pct": _num(metrics.get("drawdown_pct")),
        "higher_low": 1 if metrics.get("higher_low") is True else 0 if metrics.get("higher_low") is False else None,
        "higher_high": 1 if metrics.get("higher_high") is True else 0 if metrics.get("higher_high") is False else None,
        "smart_money_quality": str(smart_money.get("quality") or components.get("smart_money_quality") or "LOW"),
        "smart_money_points": _num(smart_money.get("quality_points") if smart_money.get("quality_points") is not None else components.get("smart_money_points")),
        "independent_buyers": int(_num(components.get("independent_buyers")) or 0),
        "buy_value_nok": _num(components.get("buy_value_nok")) or 0.0,
        "event_count": int(event_risk.get("count") or 0),
        "critical_event_count": int(event_risk.get("critical_count") or 0),
        "max_materiality_ratio_pct": max(materiality) if materiality else None,
        "benchmark_id": market.BENCHMARK_ID if benchmark_context else None,
        "benchmark_symbol": benchmark_symbol if benchmark_context else None,
        "benchmark_entry_date": benchmark_context.get("benchmark_entry_date"),
        "benchmark_entry_close": _num(benchmark_context.get("benchmark_entry_close")),
        "market_regime": benchmark_context.get("regime"),
        "benchmark_ret20_pct": _num(benchmark_context.get("benchmark_ret20_pct")),
        "benchmark_ma50_gap_pct": _num(benchmark_context.get("benchmark_ma50_gap_pct")),
        "prior_evidence_n": int(prior_evidence.get("sample_n") or 0),
        "prior_benchmark_n": int(prior_evidence.get("benchmark_sample_n") or 0),
        "prior_mean_excess_return_pct": _num(prior_evidence.get("mean_excess_return_pct")),
        "prior_median_excess_return_pct": _num(prior_evidence.get("median_excess_return_pct")),
        "prior_positive_excess_rate_pct": _num(prior_evidence.get("positive_excess_rate_pct")),
        "prior_median_max_drawdown_pct": _num(prior_evidence.get("median_max_drawdown_pct")),
        "prior_median_max_runup_pct": _num(prior_evidence.get("median_max_runup_pct")),
        "feature_payload": json.dumps(feature_payload, ensure_ascii=False, separators=(",", ":"), default=str),
    }


def capture_snapshot(result):
    if not isinstance(result, dict) or result.get("status") != "ok":
        return {"captured": False, "reason": "invalid_result"}
    ticker = str(result.get("ticker") or "").upper().replace(".OL", "")
    market_date = _market_date(result)
    if not ticker or not market_date:
        return {"captured": False, "reason": "missing_ticker_or_market_date"}

    conn = connect()
    try:
        existing = conn.execute(
            "SELECT id FROM high_conviction_shadow_snapshots WHERE model_version=? AND ticker=? AND market_date=?",
            (MODEL_VERSION, ticker, market_date),
        ).fetchone()
    finally:
        conn.close()
    if existing:
        return {"captured": False, "reason": "already_captured", "snapshot_id": existing["id"]}

    item = _point_in_time_features(result)
    columns = (
        "model_version","source_signal_model_id","ticker","market_date","observed_at","entry_price",
        "base_score","fundamentals","valuation","sentiment","insider_score","opportunity_label",
        "opportunity_score","opportunity_confidence","reversal_score","reversal_regime","rsi14",
        "macd_histogram","volume_ratio","volume_confirmation","current_drawdown_pct","higher_low",
        "higher_high","smart_money_quality","smart_money_points","independent_buyers","buy_value_nok",
        "event_count","critical_event_count","max_materiality_ratio_pct","benchmark_id","benchmark_symbol",
        "benchmark_entry_date","benchmark_entry_close","market_regime","benchmark_ret20_pct",
        "benchmark_ma50_gap_pct","prior_evidence_n","prior_benchmark_n","prior_mean_excess_return_pct",
        "prior_median_excess_return_pct","prior_positive_excess_rate_pct","prior_median_max_drawdown_pct",
        "prior_median_max_runup_pct","feature_payload"
    )
    placeholders = ",".join("?" for _ in columns)
    conn = connect()
    try:
        cur = conn.execute(
            f"INSERT INTO high_conviction_shadow_snapshots({','.join(columns)},created_at) VALUES({placeholders},?) "
            "ON CONFLICT(model_version,ticker,market_date) DO NOTHING",
            tuple(item[column] for column in columns) + (_now(),),
        )
        conn.commit()
        row = conn.execute(
            "SELECT id FROM high_conviction_shadow_snapshots WHERE model_version=? AND ticker=? AND market_date=?",
            (MODEL_VERSION, ticker, market_date),
        ).fetchone()
        return {
            "captured": bool(getattr(cur, "rowcount", 0)),
            "snapshot_id": row["id"] if row else None,
            "ticker": ticker,
            "market_date": market_date,
        }
    finally:
        conn.close()


def _forward_outcome(snapshot, rows, benchmark_rows, horizon):
    market_date = str(snapshot.get("market_date") or "")
    start_idx = next((i for i, row in enumerate(rows or []) if str(row.get("date") or "") >= market_date), None)
    if start_idx is None or start_idx + horizon >= len(rows):
        return None
    entry = _num(snapshot.get("entry_price")) or _num(rows[start_idx].get("close"))
    target = rows[start_idx + horizon]
    target_price = _num(target.get("close"))
    if not entry or entry <= 0 or not target_price or target_price <= 0:
        return None

    path_prices = [_num(row.get("close")) for row in rows[start_idx + 1:start_idx + horizon + 1]]
    path_returns = [((price / entry) - 1.0) * 100.0 for price in path_prices if price and price > 0]
    raw_return = ((target_price / entry) - 1.0) * 100.0

    benchmark_target_date = None
    benchmark_return = None
    excess = None
    if benchmark_rows and snapshot.get("benchmark_entry_close") is not None:
        market_result = market._market_return_for_target(snapshot.get("benchmark_entry_close"), target.get("date"), benchmark_rows)
        if market_result:
            benchmark_target, benchmark_return = market_result
            benchmark_target_date = benchmark_target.get("date")
            excess = raw_return - benchmark_return

    return {
        "horizon_days": horizon,
        "target_date": target.get("date"),
        "target_price": target_price,
        "return_pct": raw_return,
        "benchmark_target_date": benchmark_target_date,
        "benchmark_return_pct": benchmark_return,
        "excess_return_pct": excess,
        "max_drawdown_pct": min(path_returns) if path_returns else None,
        "max_runup_pct": max(path_returns) if path_returns else None,
    }


def settle_outcomes(ticker, stock_rows=None):
    ticker = str(ticker or "").upper().replace(".OL", "")
    if not ticker:
        return 0
    rows = stock_rows if stock_rows is not None else tracking._history(YahooProvider(), ticker)
    if not rows:
        return 0
    try:
        _, benchmark_rows = market._benchmark_rows()
    except Exception:
        benchmark_rows = []

    conn = connect()
    try:
        snapshots = [dict(row) for row in conn.execute(
            "SELECT * FROM high_conviction_shadow_snapshots WHERE ticker=? ORDER BY market_date,id",
            (ticker,),
        ).fetchall()]
        existing_rows = conn.execute(
            "SELECT o.snapshot_id,o.horizon_days FROM high_conviction_shadow_outcomes o "
            "JOIN high_conviction_shadow_snapshots s ON s.id=o.snapshot_id WHERE s.ticker=?",
            (ticker,),
        ).fetchall()
        existing = {(int(row["snapshot_id"]), int(row["horizon_days"])) for row in existing_rows}
        settled = 0
        for snapshot in snapshots:
            sid = int(snapshot["id"])
            for horizon in HORIZONS:
                if (sid, horizon) in existing:
                    continue
                item = _forward_outcome(snapshot, rows, benchmark_rows, horizon)
                if not item:
                    continue
                conn.execute(
                    "INSERT INTO high_conviction_shadow_outcomes(snapshot_id,horizon_days,target_date,target_price,return_pct,benchmark_target_date,benchmark_return_pct,excess_return_pct,max_drawdown_pct,max_runup_pct,settled_at) "
                    "VALUES(?,?,?,?,?,?,?,?,?,?,?) ON CONFLICT(snapshot_id,horizon_days) DO NOTHING",
                    (sid, horizon, item["target_date"], item["target_price"], item["return_pct"],
                     item["benchmark_target_date"], item["benchmark_return_pct"], item["excess_return_pct"],
                     item["max_drawdown_pct"], item["max_runup_pct"], _now()),
                )
                existing.add((sid, horizon))
                settled += 1
        conn.commit()
        return settled
    finally:
        conn.close()


def dataset_status(ticker=None):
    ticker = str(ticker or "").upper().replace(".OL", "") or None
    where = " WHERE ticker=?" if ticker else ""
    params = (ticker,) if ticker else ()
    conn = connect()
    try:
        snap = conn.execute(
            "SELECT COUNT(*) AS n,COUNT(DISTINCT ticker) AS tickers,MIN(market_date) AS first_date,MAX(market_date) AS last_date "
            f"FROM high_conviction_shadow_snapshots{where}", params,
        ).fetchone()
        outcomes = conn.execute(
            "SELECT o.horizon_days,COUNT(*) AS n,SUM(CASE WHEN o.excess_return_pct IS NOT NULL THEN 1 ELSE 0 END) AS alpha_n "
            "FROM high_conviction_shadow_outcomes o JOIN high_conviction_shadow_snapshots s ON s.id=o.snapshot_id" +
            (" WHERE s.ticker=?" if ticker else "") + " GROUP BY o.horizon_days ORDER BY o.horizon_days",
            params,
        ).fetchall()
        recent = conn.execute(
            "SELECT id,ticker,market_date,observed_at,base_score,opportunity_label,opportunity_score,reversal_regime,"
            "smart_money_quality,event_count,critical_event_count,market_regime,prior_evidence_n "
            "FROM high_conviction_shadow_snapshots" + (" WHERE ticker=?" if ticker else "") +
            " ORDER BY market_date DESC,id DESC LIMIT 10",
            params,
        ).fetchall()
    finally:
        conn.close()
    snap = dict(snap) if snap else {}
    return {
        "status": "ok",
        "dataset": MODEL_VERSION,
        "ticker": ticker,
        "snapshots": int(snap.get("n") or 0),
        "tickers": int(snap.get("tickers") or 0),
        "first_market_date": snap.get("first_date"),
        "last_market_date": snap.get("last_date"),
        "forward_outcomes": {
            str(row["horizon_days"]): {"n": int(row["n"] or 0), "alpha_n": int(row["alpha_n"] or 0)}
            for row in outcomes
        },
        "recent_snapshots": [dict(row) for row in recent],
        "selection_unit": "daily point-in-time snapshot",
        "independence_warning": "Daily snapshots are correlated observations. Future activation tests must pre-register a candidate rule and de-correlate contiguous candidate episodes before inference.",
        "activation_enabled": False,
        "automatic_threshold_changes": False,
        "meaning": "Forward research dataset only. It does not drive live signals or portfolio actions.",
        "generated_at": _now(),
    }


def _live_with_dataset(ticker):
    result = _BASE_LIVE(ticker)
    try:
        capture_snapshot(result)
    except Exception:
        log.exception("High Conviction point-in-time snapshot failed for %s", ticker)
    return result


def _settle_with_dataset(ticker, rows=None):
    history = rows
    if history is None:
        try:
            history = tracking._history(YahooProvider(), ticker)
        except Exception:
            history = None
    settled = _BASE_SETTLE(ticker, rows=history)
    try:
        settle_outcomes(ticker, stock_rows=history)
    except Exception:
        log.exception("High Conviction outcome settlement failed for %s", ticker)
    return settled


def install():
    if getattr(extra_api, "_high_conviction_shadow_dataset_v2", False):
        return
    _ensure_schema()
    opportunity.live_opportunity = _live_with_dataset
    tracking.settle_forward_returns = _settle_with_dataset

    original_install = extra_api.install

    def patched_install(app):
        original_install(app)

        @app.get("/api/high-conviction-shadow-dataset/status")
        def high_conviction_shadow_dataset_status():
            return dataset_status()

        @app.get("/api/high-conviction-shadow-dataset/{ticker}")
        def high_conviction_shadow_dataset_ticker(ticker: str):
            return dataset_status(ticker)

    extra_api.install = patched_install
    extra_api._high_conviction_shadow_dataset_v2 = True


install()
