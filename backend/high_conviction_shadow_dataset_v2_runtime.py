"""Point-in-time High Conviction research dataset.

Every successful Opportunity scan is eligible for one immutable daily snapshot per
High Conviction model/ticker/market day. The snapshot freezes only information that
was available at capture time. Forward outcomes are settled later against OSEBX.

This module is measurement-only: it cannot alter scores, Opportunity labels,
thresholds, push eligibility, position sizing, or emit a buy/sell recommendation.
"""
