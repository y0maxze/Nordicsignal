"""User-entered holdings portfolio, transaction ledger and account-aware tax tracking.

Holdings mirror real broker positions and stay separate from paper trading. ASK tax
tracking is account-level: deposits are treated as withdrawn first, while internal
buys/sells/dividends on ASK do not themselves create a taxable event. The ledger
therefore records cash flows separately from the current position snapshot.
"""
from datetime import date, datetime, timezone
from typing import Literal

from fastapi import HTTPException
from pydantic import BaseModel, Field, model_validator

import extra_api
from database import connect, USING_POSTGRES
from providers import YahooProvider

ASK_TAX_RATE_2026 = 0.3784
TX_TYPES = {'deposit', 'withdrawal', 'buy', 'sell', 'dividend'}


def _now():
    return datetime.now(timezone.utc).isoformat()


def _clean_text(value, fallback):
    text = ' '.join(str(value or '').split()).strip()
    return text or fallback


